def split_amount(total, parts):
    """Split an integer amount into `parts` positive integers summing exactly to total."""
    if parts == 1 or total < parts * 10:
        return [total]
    cuts = sorted(random.sample(range(10, total - 9), parts - 1))
    values = [b - a for a, b in zip([0] + cuts, cuts + [total])]
    return values if all(v > 0 for v in values) else [total]


def raised_for(funding, cost):
    if funding == "open":
        return 0
    if funding == "partial":
        return int(round(cost * random.uniform(0.2, 0.6) / 5) * 5)
    if funding == "almost":
        return int(round(cost * random.uniform(0.80, 0.95) / 5) * 5)
    return cost  # funded / delivered


def status_for(funding, raised, cost):
    if funding == "delivered":
        return "delivered"
    if raised >= cost:
        return "funded"
    return "partially_funded" if raised > 0 else "open"


