ENUM_ARRAY_COLUMNS = {
    "preferred_categories": "wish_category[]",
    "needed_categories": "wish_category[]",
}


def escape(val, col_name=None):
    if isinstance(val, Raw):
        return str(val)
    if val is None:
        return "NULL"
    if isinstance(val, bool):
        return "TRUE" if val else "FALSE"
    if isinstance(val, (int, float)):
        return str(val)
    if isinstance(val, list):
        items = ",".join("'" + str(v).replace("'", "''") + "'" for v in val)
        literal = f"ARRAY[{items}]"
        if col_name in ENUM_ARRAY_COLUMNS:
            literal += f"::{ENUM_ARRAY_COLUMNS[col_name]}"
        return literal
    return "'" + str(val).replace("'", "''") + "'"


def to_sql_inserts(table, rows):
    if not rows:
        return ""
    cols = list(rows[0].keys())
    values = ",\n".join("    (" + ", ".join(escape(r[c], c) for c in cols) + ")" for r in rows)
    return f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n{values};\n"


