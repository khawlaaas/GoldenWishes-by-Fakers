def gen_wishes_and_donations(orgs_by_key, donors):
    beneficiaries, wishes, donations = [], [], []
    used_names = {"F": set(), "M": set()}
    donor_totals = {d["id"]: 0 for d in donors}

    for (key, gender, ages, situation, category, cost, urgency, funding, tags,
         title, description, story) in WISHES:
        org = orgs_by_key[key]
        pool = GIRL_NAMES if gender == "F" else BOY_NAMES
        free = [n for n in pool if n not in used_names[gender]] or pool
        nickname = random.choice(free)
        used_names[gender].add(nickname)
        age = random.randint(*ages)

        beneficiary = {
            "id": str(uuid.uuid4()),
            "organization_id": org["id"],
            "nickname": nickname,
            "age": age,
            "gender": gender,
            "situation": situation,
            "health_note": "Regular medical follow-up" if category == "health" else None,
            "created_at": iso(NOW - timedelta(days=random.randint(30, 200))),
        }
        beneficiaries.append(beneficiary)

        created = NOW - timedelta(days=random.randint(3, 120))
        raised = raised_for(funding, cost)
        wish_id = str(uuid.uuid4())

        # Donations always add up exactly to amount_raised.
        for amount in split_amount(raised, random.randint(1, 3)) if raised > 0 else []:
            donor = random.choice(donors)
            donor_totals[donor["id"]] += amount
            donations.append({
                "id": str(uuid.uuid4()),
                "donor_id": donor["id"],
                "wish_id": wish_id,
                "amount": amount,
                "donated_at": iso(created + timedelta(days=random.randint(0, 2), hours=random.randint(1, 20))),
                "message": random.choice([None, "Wishing you all the best!", "With love.", "For your smile.", None]),
                "donor_display_name": random.choice([donor["full_name"].split()[0], None]),
                "is_demo": False,
            })

        wishes.append({
            "id": wish_id,
            "beneficiary_id": beneficiary["id"],
            "organization_id": org["id"],
            "category": category,
            "title": title,
            "description": description,
            "story_context": story.format(name=nickname, age=age),
            "estimated_cost": cost,
            "amount_raised": raised,
            "currency": "MAD",
            "urgency": urgency,
            "status": status_for(funding, raised, cost),
            "relay_point": org["relay_point"],
            "city": org["city"],
            "region": org["region"],
            "country": "Morocco",
            "country_code": "MA",
            "tags": tags,
            "deadline": (NOW + timedelta(days=random.randint(7, 60))).date().isoformat()
            if urgency in ("high", "critical") and funding not in ("funded", "delivered") else None,
            "submission_source": "seed",
            "created_at": iso(created),
        })

    for d in donors:
        d["total_donated"] = donor_totals[d["id"]]
    return beneficiaries, wishes, donations


