#!/usr/bin/env node
/* Regenerate the offline seed from the database, so DATA_SOURCE = 'local' shows the same data.
 * Usage:  node scripts/export-local-seed.js
 * Writes js/data/seed-offers.js (public wishes + pending ones, WITHOUT raw_submission) and js/data/seed-news.js.
 * The rows keep the API shape; js/data/mapping.js maps them for both data sources.
 */
const fs = require('fs');
const path = require('path');
require('./env').loadEnv();
const { query } = require('../netlify/lib/db');
const { publicWishes, news, REVIEW_COLUMNS, REVIEW_FROM } = require('../netlify/lib/wishes');

const ROOT = path.join(__dirname, '..');

function write(file, globalName, rows, comment) {
    const body = `/* Golden Wishes — ${comment}
 * GENERATED by scripts/export-local-seed.js from the database on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
 * Used only when DATA_SOURCE = 'local' in js/data/store.js (offline fallback).
 */
(function (root) {
    var ROWS = ${JSON.stringify(rows, null, 1)};
    if (typeof module !== 'undefined' && module.exports) module.exports = ROWS;
    if (root) { root.GW = root.GW || {}; root.GW.${globalName} = ROWS; }
})(typeof window !== 'undefined' ? window : null);
`;
    fs.writeFileSync(path.join(ROOT, file), body);
    console.log(`Wrote ${rows.length} rows to ${file}`);
}

async function main() {
    const wishes = await publicWishes();
    const pending = (await query(`SELECT ${REVIEW_COLUMNS} FROM ${REVIEW_FROM} WHERE w.status = 'pending_review' ORDER BY w.created_at`)).rows;
    if (pending.some((r) => 'raw_submission' in r)) throw new Error('raw_submission must never be exported');
    write('js/data/seed-offers.js', 'SEED_OFFERS', wishes.concat(pending), 'wishes snapshot (public columns only)');
    write('js/data/seed-news.js', 'SEED_NEWS', await news(), 'news snapshot (sample data)');
}

main().then(() => process.exit(0)).catch((err) => { console.error(err.message); process.exit(1); });
